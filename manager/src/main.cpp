    // Enable or disable every mod in the profile at once.
    svr.Post("/api/profile/:id/mods/toggle-all", [](const httplib::Request& req, httplib::Response& res) {
        std::lock_guard<std::mutex> g(gLock);
        Profile* p = findProfile(req.path_params.at("id"));
        if (!p)
            return sendError(res, 404, "Profile not found");
        json j = json::parse(req.body, nullptr, false);
        if (!j.is_object() || !j.contains("enabled") || !j["enabled"].is_boolean())
            return sendError(res, 400, "Invalid JSON");
        bool enable = j["enabled"].get<bool>();
        if (isRunning(*p))
            return sendError(res, 409, "Stop the game before changing mods (BeamNG keeps its mod files open)");
        fs::path srcDir = enable ? disabledDir(*p) : modsDir(*p);
        fs::path dstDir = enable ? modsDir(*p) : disabledDir(*p);
        std::vector<fs::path> files;
        std::error_code ec;
        for (auto& e : fs::directory_iterator(srcDir, ec))
            if (e.is_regular_file(ec) && validModName(S(e.path().filename())))
                files.push_back(e.path());
        int moved = 0, failed = 0;
        for (auto& f : files) {
            std::error_code mec;
            if (moveMod(f, dstDir / f.filename(), mec))
                moved++;
            else
                failed++;
        }
        sendJson(res, { { "moved", moved }, { "failed", failed } });
    });

