    svr.set_pre_routing_handler([boundPort](const httplib::Request& req, httplib::Response& res) {
        std::string host = req.get_header_value("Host");
        std::string a = "127.0.0.1:" + std::to_string(boundPort);
        std::string b = "localhost:" + std::to_string(boundPort);
        if (host != a && host != b) {
            res.status = 403;
            res.set_content("Forbidden", "text/plain");
            return httplib::Server::HandlerResponse::Handled;
        }
        if (req.method != "GET" && req.method != "HEAD" && req.get_header_value("X-BMM") != "1") {
            res.status = 403;
            res.set_content("Forbidden", "text/plain");
            return httplib::Server::HandlerResponse::Handled;
        }
        return httplib::Server::HandlerResponse::Unhandled;
    });

    svr.set_exception_handler([](const httplib::Request&, httplib::Response& res, std::exception_ptr ep) {
        std::string msg = "Internal error";
        try {
            if (ep)
                std::rethrow_exception(ep);
        } catch (const std::exception& e) {
            msg = e.what();
        } catch (...) {
        }
        sendError(res, 500, msg);
    });

