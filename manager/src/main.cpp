    svr.Post("/api/profile", [](const httplib::Request& req, httplib::Response& res) {
        std::lock_guard<std::mutex> g(gLock);
        json j = json::parse(req.body, nullptr, false);
        if (!j.is_object())
            return sendError(res, 400, "Invalid JSON");
        Profile p;
        p.name = j.value("name", "");
        while (!p.name.empty() && std::isspace((unsigned char)p.name.back()))
            p.name.pop_back();
        if (p.name.empty() || p.name.size() > 60)
            return sendError(res, 400, "Give the profile a name (max 60 characters)");
        for (auto& o : gProfiles)
            if (lower(o.name) == lower(p.name))
                return sendError(res, 409, "A profile with that name already exists");
        std::string base = slugify(p.name);
        do {
            p.id = base + "-" + randomHex(4);
        } while (findProfile(p.id));
        p.notes = j.value("notes", "");
        p.gameArgs = j.value("gameArgs", "");
        p.created = nowIso();
        p.port = j.value("port", 0);
        if (p.port <= 0)
            p.port = nextFreePort();
        if (p.port < 1024 || p.port > 65000)
            return sendError(res, 400, "Port must be between 1024 and 65000");

        std::error_code ec;
        fs::create_directories(modsDir(p), ec);
        fs::create_directories(disabledDir(p), ec);
        fs::create_directories(instanceDir(p), ec);

        std::string cloneFrom = j.value("cloneFrom", "");
        if (!cloneFrom.empty()) {
            Profile* src = findProfile(cloneFrom);
            if (!src)
                return sendError(res, 404, "Profile to clone was not found");
            // Mods (except BeamMP's own downloaded server mods), disabled mods and settings.
            copyTree(modsDir(*src), modsDir(p), "multiplayer");
            copyTree(disabledDir(*src), disabledDir(p), "");
            copyTree(userDir(*src) / "current" / "settings", userDir(p) / "current" / "settings", "");
            if (j.value("copyLogin", false) && fs::exists(instanceDir(*src) / "key", ec))
                fs::copy_file(instanceDir(*src) / "key", instanceDir(p) / "key", fs::copy_options::overwrite_existing, ec);
        }
        gProfiles.push_back(p);
        saveStore();
        sendJson(res, profileJson(p, true), 201);
    });

    svr.Put("/api/profile/:id", [](const httplib::Request& req, httplib::Response& res) {
        std::lock_guard<std::mutex> g(gLock);
        Profile* p = findProfile(req.path_params.at("id"));
        if (!p)
            return sendError(res, 404, "Profile not found");
        json j = json::parse(req.body, nullptr, false);
        if (!j.is_object())
            return sendError(res, 400, "Invalid JSON");
        if (j.contains("name")) {
            std::string n = j["name"].get<std::string>();
            if (n.empty() || n.size() > 60)
                return sendError(res, 400, "Give the profile a name (max 60 characters)");
            for (auto& o : gProfiles)
                if (&o != p && lower(o.name) == lower(n))
                    return sendError(res, 409, "A profile with that name already exists");
            p->name = n;
        }
        if (j.contains("notes"))
            p->notes = j["notes"].get<std::string>();
        if (j.contains("gameArgs"))
            p->gameArgs = j["gameArgs"].get<std::string>();
        if (j.contains("offline") && j["offline"].is_boolean())
            p->offline = j["offline"].get<bool>();
        if (j.contains("offlineName") && j["offlineName"].is_string())
            p->offlineName = cleanText(j["offlineName"].get<std::string>()).substr(0, 32);
        if (j.contains("port")) {
            int port = j["port"].get<int>();
            if (port < 1024 || port > 65000)
                return sendError(res, 400, "Port must be between 1024 and 65000");
            for (auto& o : gProfiles)
                if (&o != p && (o.port == port || o.port == port + 1 || o.port + 1 == port))
                    return sendError(res, 409, "Another profile already uses that port (a launcher uses the port and port+1)");
            if (isRunning(*p) && port != p->port)
                return sendError(res, 409, "Stop the profile before changing its port");
            p->port = port;
        }
        saveStore();
        sendJson(res, profileJson(*p, true));
    });

    svr.Delete("/api/profile/:id", [](const httplib::Request& req, httplib::Response& res) {
        std::lock_guard<std::mutex> g(gLock);
        Profile* p = findProfile(req.path_params.at("id"));
        if (!p)
            return sendError(res, 404, "Profile not found");
        if (isRunning(*p))
            return sendError(res, 409, "Stop the profile before deleting it");
        std::error_code ec;
        fs::remove_all(profileRoot(*p), ec);
        std::string id = p->id;
        gProfiles.erase(std::remove_if(gProfiles.begin(), gProfiles.end(), [&](const Profile& x) { return x.id == id; }), gProfiles.end());
        saveStore();
        bool serversChanged = false;
        for (auto& sv : gServers)
            if (sv.syncProfile == id) {
                sv.syncProfile = "";
                serversChanged = true;
            }
        if (serversChanged)
            saveServers();
        sendJson(res, { { "ok", true } });
    });

    svr.Post("/api/profile/:id/launch", [](const httplib::Request& req, httplib::Response& res) {
        std::lock_guard<std::mutex> g(gLock);
        Profile* p = findProfile(req.path_params.at("id"));
        if (!p)
            return sendError(res, 404, "Profile not found");
        if (isRunning(*p))
            return sendError(res, 409, "This profile is already running");
        fs::path launcher = resolveLauncher();
        if (launcher.empty())
            return sendError(res, 400, "BeamMP-Launcher was not found. Put BeamMP-Manager next to BeamMP-Launcher, or set its path in Settings.");
        if (!portFree(p->port) || !portFree(p->port + 1))
            return sendError(res, 409, "Port " + std::to_string(p->port) + " (or " + std::to_string(p->port + 1)
                    + ") is already in use. Close the other launcher or change this profile's port.");

        std::error_code ec;
        fs::create_directories(modsDir(*p), ec);
        fs::create_directories(disabledDir(*p), ec);
        fs::create_directories(instanceDir(*p), ec);
        writeLauncherPortSetting(*p);

        std::string user = S(userDir(*p));
        std::vector<std::string> args = { "--port", std::to_string(p->port), "--user-path", user,
            "--no-update", // never let the upstream auto-updater replace this fork
            "--" };
        if (p->offline) { // no BeamMP login/update/download; for private direct-connect servers
            args.insert(args.begin(), { "--offline", "--name", p->offlineName.empty() ? p->name : p->offlineName });
        }
        args.push_back("-userpath");
        args.push_back(user);
        for (auto& a : splitArgs(p->gameArgs))
            args.push_back(a);

        std::string err;
        long pid = spawnLauncher(launcher, args, instanceDir(*p), instanceDir(*p), err);
        if (pid < 0)
            return sendError(res, 500, "Could not start the launcher: " + err);
        gPids[p->id] = pid;
        writeFile(instanceDir(*p) / "manager.pid", std::to_string(pid));
        sendJson(res, profileJson(*p, false));
    });

