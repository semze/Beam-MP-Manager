static void sendJson(httplib::Response& res, const json& j, int status = 200) {
    res.status = status;
    res.set_header("Cache-Control", "no-store");
    res.set_content(j.dump(), "application/json; charset=utf-8");
}

static void sendError(httplib::Response& res, int status, const std::string& msg) {
    sendJson(res, { { "error", msg } }, status);
}

static json profileJson(const Profile& p, bool withCounts) {
    json j = { { "id", p.id }, { "name", p.name }, { "notes", p.notes }, { "gameArgs", p.gameArgs },
        { "created", p.created }, { "port", p.port }, { "offline", p.offline }, { "offlineName", p.offlineName } };
    auto it = gPids.find(p.id);
    bool running = isRunning(p);
    j["running"] = running;
    j["pid"] = running ? it->second : 0;
    if (withCounts) {
        int en = 0, dis = 0;
        std::error_code ec;
        for (auto& e : fs::directory_iterator(modsDir(p), ec))
            if (e.is_regular_file() && validModName(S(e.path().filename())))
                en++;
        for (auto& e : fs::directory_iterator(disabledDir(p), ec))
            if (e.is_regular_file() && validModName(S(e.path().filename())))
                dis++;
        j["modCount"] = en;
        j["disabledCount"] = dis;
    }
    return j;
}

static json listMods(const Profile& p) {
    json arr = json::array();
    std::error_code ec;
    auto scan = [&](const fs::path& dir, bool enabled) {
        for (auto& e : fs::directory_iterator(dir, ec)) {
            if (!e.is_regular_file(ec))
                continue;
            std::string name = S(e.path().filename());
            if (!validModName(name))
                continue;
            std::error_code ec2;
            arr.push_back({ { "name", name }, { "size", (long long)e.file_size(ec2) }, { "enabled", enabled } });
        }
    };
    scan(modsDir(p), true);
    scan(disabledDir(p), false);
    std::sort(arr.begin(), arr.end(), [](const json& a, const json& b) {
        return lower(a["name"].get<std::string>()) < lower(b["name"].get<std::string>());
    });
    return arr;
}

// Moves a mod file between the enabled and disabled folders. A same-named file already at the
// destination is replaced (same file name = same mod; also keeps Windows rename() happy).
static bool moveMod(const fs::path& from, const fs::path& to, std::error_code& ec) {
    fs::create_directories(to.parent_path(), ec);
    ec.clear();
    fs::remove(to, ec);
    ec.clear();
    fs::rename(from, to, ec);
    return !ec;
}

// Make sure the in-game BeamMP mod will connect to *this* instance's launcher port.
// The BeamMP Lua mod reads the "launcherPort" game setting.
static void writeLauncherPortSetting(const Profile& p) {
    fs::path dir = userDir(p) / "current" / "settings";
    std::error_code ec;
    fs::create_directories(dir, ec);
    fs::path f = dir / "settings.json";
    json j = json::object();
    if (fs::exists(f, ec)) {
        json parsed = json::parse(readFile(f), nullptr, false);
        if (parsed.is_object())
            j = parsed;
        else
            return; // do not clobber a file we cannot parse
    }
    j["launcherPort"] = p.port;
    writeFile(f, j.dump(2));
}

static std::string tailLines(const fs::path& f, int maxLines) {
    std::ifstream in(f, std::ios::binary);
    if (!in.is_open())
        return "";
    in.seekg(0, std::ios::end);
    std::streamoff size = in.tellg();
    std::streamoff start = size > 262144 ? size - 262144 : 0;
    in.seekg(start);
    std::string data((size_t)(size - start), '\0');
    in.read(data.data(), (std::streamsize)data.size());
    std::vector<std::string> lines;
    std::stringstream ss(data);
    std::string line;
    while (std::getline(ss, line))
        lines.push_back(line);
    size_t from = lines.size() > (size_t)maxLines ? lines.size() - (size_t)maxLines : 0;
    std::string out;
    for (size_t i = from; i < lines.size(); i++)
        out += lines[i] + "\n";
    return out;
}

