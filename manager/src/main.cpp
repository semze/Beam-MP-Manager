static fs::path P(const std::string& s) {
#if defined(__cpp_char8_t)
    return fs::path(std::u8string(s.begin(), s.end()));
#else
    return fs::u8path(s);
#endif
}

static std::string S(const fs::path& p) {
#if defined(__cpp_char8_t)
    auto u = p.u8string();
    return std::string(u.begin(), u.end());
#else
    return p.u8string();
#endif
}

static std::string lower(std::string s) {
    std::transform(s.begin(), s.end(), s.begin(), [](unsigned char c) { return (char)std::tolower(c); });
    return s;
}

static std::string nowIso() {
    std::time_t t = std::time(nullptr);
    std::tm tm {};
    if (const std::tm* g = std::gmtime(&t)) // only called while holding gLock
        tm = *g;
    char buf[32];
    std::strftime(buf, sizeof(buf), "%Y-%m-%dT%H:%M:%SZ", &tm);
    return buf;
}

static std::string slugify(const std::string& name) {
    std::string out;
    for (unsigned char c : name) {
        if (std::isalnum(c))
            out += (char)std::tolower(c);
        else if (!out.empty() && out.back() != '-')
            out += '-';
    }
    while (!out.empty() && out.back() == '-')
        out.pop_back();
    if (out.size() > 24)
        out.resize(24);
    while (!out.empty() && out.back() == '-')
        out.pop_back();
    return out.empty() ? "profile" : out;
}

static std::string randomHex(int n) {
    static std::mt19937 rng { std::random_device {}() };
    static const char* digits = "0123456789abcdef";
    std::string s;
    for (int i = 0; i < n; i++)
        s += digits[rng() % 16];
    return s;
}

static bool validId(const std::string& id) {
    if (id.empty() || id.size() > 64)
        return false;
    for (unsigned char c : id)
        if (!(std::isalnum(c) || c == '-' || c == '_'))
            return false;
    return true;
}

// A mod file name must be a plain file name ending in .zip
static bool validModName(const std::string& name) {
    if (name.empty() || name.size() > 200)
        return false;
    if (name.find('/') != std::string::npos || name.find('\\') != std::string::npos || name.find("..") != std::string::npos)
        return false;
    if (name.find(':') != std::string::npos || name.find('\0') != std::string::npos)
        return false;
    if (name.front() == '.' || name.front() == ' ')
        return false;
    return lower(name).size() > 4 && lower(name).substr(lower(name).size() - 4) == ".zip";
}

static std::vector<std::string> splitArgs(const std::string& s) {
    std::vector<std::string> out;
    std::string cur;
    bool inQuote = false, have = false;
    for (char c : s) {
        if (c == '"') {
            inQuote = !inQuote;
            have = true;
        } else if (std::isspace((unsigned char)c) && !inQuote) {
            if (have) {
                out.push_back(cur);
                cur.clear();
                have = false;
            }
        } else {
            cur += c;
            have = true;
        }
    }
    if (have)
        out.push_back(cur);
    return out;
}

static std::string readFile(const fs::path& p) {
    std::ifstream f(p, std::ios::binary);
    std::stringstream ss;
    ss << f.rdbuf();
    return ss.str();
}

static bool writeFile(const fs::path& p, const std::string& data) {
    std::ofstream f(p, std::ios::binary | std::ios::trunc);
    if (!f.is_open())
        return false;
    f << data;
    return f.good();
}

#if defined(_WIN32)
static std::wstring widen(const std::string& s) {
    if (s.empty())
        return L"";
    int n = MultiByteToWideChar(CP_UTF8, 0, s.data(), (int)s.size(), nullptr, 0);
    std::wstring w(n, 0);
    MultiByteToWideChar(CP_UTF8, 0, s.data(), (int)s.size(), w.data(), n);
    return w;
}
static std::wstring quoteArg(const std::wstring& a) {
    if (!a.empty() && a.find_first_of(L" \t\"") == std::wstring::npos)
        return a;
    std::wstring r = L"\"";
    for (wchar_t c : a) {
        if (c == L'"')
            r += L"\\\"";
        else
            r += c;
    }
    r += L"\"";
    return r;
}
#endif

