static bool portFree(int port) {
#if defined(_WIN32)
    SOCKET s = socket(AF_INET, SOCK_STREAM, IPPROTO_TCP);
    if (s == INVALID_SOCKET)
        return true;
    sockaddr_in a {};
    a.sin_family = AF_INET;
    a.sin_addr.s_addr = htonl(INADDR_ANY);
    a.sin_port = htons((u_short)port);
    bool ok = bind(s, (sockaddr*)&a, sizeof(a)) == 0;
    closesocket(s);
    return ok;
#else
    int s = socket(AF_INET, SOCK_STREAM, 0);
    if (s < 0)
        return true;
    int one = 1;
    setsockopt(s, SOL_SOCKET, SO_REUSEADDR, &one, sizeof(one));
    sockaddr_in a {};
    a.sin_family = AF_INET;
    a.sin_addr.s_addr = htonl(INADDR_ANY);
    a.sin_port = htons((uint16_t)port);
    bool ok = bind(s, (sockaddr*)&a, sizeof(a)) == 0;
    close(s);
    return ok;
#endif
}

static bool pidAlive(long pid) {
    if (pid <= 0)
        return false;
#if defined(_WIN32)
    HANDLE h = OpenProcess(PROCESS_QUERY_LIMITED_INFORMATION, FALSE, (DWORD)pid);
    if (!h)
        return false;
    DWORD code = 0;
    bool alive = GetExitCodeProcess(h, &code) && code == STILL_ACTIVE;
    CloseHandle(h);
    return alive;
#else
    int status = 0;
    pid_t r = waitpid((pid_t)pid, &status, WNOHANG); // reaps our own finished children
    if (r == (pid_t)pid)
        return false;
    return kill((pid_t)pid, 0) == 0;
#endif
}

static void killTree(long pid) {
    if (pid <= 0)
        return;
#if defined(_WIN32)
    // /T also ends the BeamNG process the launcher started
    std::wstring cmd = L"taskkill /PID " + std::to_wstring(pid) + L" /T /F";
    STARTUPINFOW si {};
    si.cb = sizeof(si);
    si.dwFlags = STARTF_USESHOWWINDOW;
    si.wShowWindow = SW_HIDE;
    PROCESS_INFORMATION pi {};
    if (CreateProcessW(nullptr, cmd.data(), nullptr, nullptr, FALSE, CREATE_NO_WINDOW, nullptr, nullptr, &si, &pi)) {
        WaitForSingleObject(pi.hProcess, 8000);
        CloseHandle(pi.hProcess);
        CloseHandle(pi.hThread);
    }
#else
    kill(-(pid_t)pid, SIGTERM); // the launcher was started in its own process group
    kill((pid_t)pid, SIGTERM);
    for (int i = 0; i < 30 && pidAlive(pid); i++)
        std::this_thread::sleep_for(std::chrono::milliseconds(100));
    if (pidAlive(pid)) {
        kill(-(pid_t)pid, SIGKILL);
        kill((pid_t)pid, SIGKILL);
    }
#endif
}

// Starts the launcher; returns pid or -1 (error filled in).
static long spawnLauncher(const fs::path& launcher, const std::vector<std::string>& args,
    const fs::path& workDir, const fs::path& instanceDir, std::string& error) {
#if defined(_WIN32)
    static std::mutex envLock;
    std::lock_guard<std::mutex> g(envLock);
    std::wstring cmd = quoteArg(launcher.wstring());
    for (auto& a : args)
        cmd += L" " + quoteArg(widen(a));
    SetEnvironmentVariableW(L"BEAMMP_INSTANCE_DIR", instanceDir.wstring().c_str());
    STARTUPINFOW si {};
    si.cb = sizeof(si);
    PROCESS_INFORMATION pi {};
    // Each launcher gets its own console window (the launcher requires it to stay open).
    BOOL ok = CreateProcessW(nullptr, cmd.data(), nullptr, nullptr, FALSE, CREATE_NEW_CONSOLE,
        nullptr, workDir.wstring().c_str(), &si, &pi);
    DWORD err = GetLastError();
    SetEnvironmentVariableW(L"BEAMMP_INSTANCE_DIR", nullptr);
    if (!ok) {
        error = "CreateProcess failed (error " + std::to_string(err) + ")";
        return -1;
    }
    long pid = (long)pi.dwProcessId;
    CloseHandle(pi.hProcess);
    CloseHandle(pi.hThread);
    return pid;
#else
    std::vector<std::string> store;
    store.push_back(S(launcher));
    for (auto& a : args)
        store.push_back(a);
    std::vector<char*> argv;
    for (auto& s : store)
        argv.push_back(s.data());
    argv.push_back(nullptr);
    std::string wd = S(workDir), inst = S(instanceDir);
    pid_t pid = fork();
    if (pid < 0) {
        error = "fork failed";
        return -1;
    }
    if (pid == 0) {
        setsid();
        if (chdir(wd.c_str()) != 0)
            _exit(126);
        setenv("BEAMMP_INSTANCE_DIR", inst.c_str(), 1);
        int dn = open("/dev/null", O_RDWR);
        if (dn >= 0) {
            dup2(dn, 0);
            dup2(dn, 1);
            dup2(dn, 2);
        }
        execv(store[0].c_str(), argv.data());
        _exit(127);
    }
    // Give exec a moment to fail fast (bad path, not executable)
    std::this_thread::sleep_for(std::chrono::milliseconds(250));
    int status = 0;
    if (waitpid(pid, &status, WNOHANG) == pid) {
        error = "The launcher exited immediately (is it executable?)";
        return -1;
    }
    return (long)pid;
#endif
}

static void openFolder(const fs::path& dir) {
#if defined(_WIN32)
    ShellExecuteW(nullptr, L"open", dir.wstring().c_str(), nullptr, nullptr, SW_SHOWNORMAL);
#else
    std::string d = S(dir);
    pid_t pid = fork();
    if (pid == 0) {
        setsid();
        execlp("xdg-open", "xdg-open", d.c_str(), (char*)nullptr);
        _exit(127);
    }
#endif
}

static void openUrl(const std::string& url) {
#if defined(_WIN32)
    ShellExecuteW(nullptr, L"open", widen(url).c_str(), nullptr, nullptr, SW_SHOWNORMAL);
#else
    pid_t pid = fork();
    if (pid == 0) {
        setsid();
        int dn = open("/dev/null", O_RDWR);
        if (dn >= 0) {
            dup2(dn, 1);
            dup2(dn, 2);
        }
        execlp("xdg-open", "xdg-open", url.c_str(), (char*)nullptr);
        _exit(127);
    }
#endif
}

