struct Profile {
    std::string id, name, notes, gameArgs, created, offlineName;
    int port = 4444;
    bool offline = false; // launcher --offline: no BeamMP login (private direct-connect servers)
};

static std::mutex gLock;
static fs::path gDataDir;
static std::vector<Profile> gProfiles;
static std::string gLauncherPath; // user-configured path to BeamMP-Launcher(.exe)
static std::map<std::string, long> gPids; // profile id -> launcher pid

static fs::path profileRoot(const Profile& p) { return gDataDir / "profiles" / P(p.id); }
static fs::path userDir(const Profile& p) { return profileRoot(p) / "user"; }
static fs::path instanceDir(const Profile& p) { return profileRoot(p) / "instance"; }
static fs::path modsDir(const Profile& p) { return userDir(p) / "current" / "mods"; }
static fs::path disabledDir(const Profile& p) { return userDir(p) / "current" / "mods_disabled"; }

static fs::path launcherBinaryName() {
#if defined(_WIN32)
    return "BeamMP-Launcher.exe";
#else
    return "BeamMP-Launcher";
#endif
}

static fs::path resolveLauncher() {
    if (!gLauncherPath.empty()) {
        std::error_code ec;
        fs::path p = P(gLauncherPath);
        if (fs::is_regular_file(p, ec))
            return p;
    }
    std::error_code ec;
    fs::path next = exePath().parent_path() / launcherBinaryName();
    if (fs::is_regular_file(next, ec))
        return next;
    return {};
}

static void saveStore() {
    json j;
    j["version"] = 1;
    j["launcherPath"] = gLauncherPath;
    j["profiles"] = json::array();
    for (auto& p : gProfiles)
        j["profiles"].push_back({ { "id", p.id }, { "name", p.name }, { "notes", p.notes },
            { "gameArgs", p.gameArgs }, { "created", p.created }, { "port", p.port },
            { "offline", p.offline }, { "offlineName", p.offlineName } });
    std::error_code ec;
    fs::create_directories(gDataDir, ec);
    fs::path tmp = gDataDir / "profiles.json.tmp";
    if (writeFile(tmp, j.dump(2)))
        fs::rename(tmp, gDataDir / "profiles.json", ec);
}

static void loadStore() {
    gProfiles.clear();
    fs::path f = gDataDir / "profiles.json";
    std::error_code ec;
    if (!fs::exists(f, ec))
        return;
    json j = json::parse(readFile(f), nullptr, false);
    if (j.is_discarded() || !j.is_object())
        return;
    gLauncherPath = j.value("launcherPath", "");
    if (!j.contains("profiles") || !j["profiles"].is_array())
        return;
    for (auto& e : j["profiles"]) {
        Profile p;
        p.id = e.value("id", "");
        if (!validId(p.id))
            continue;
        p.name = e.value("name", p.id);
        p.notes = e.value("notes", "");
        p.gameArgs = e.value("gameArgs", "");
        p.created = e.value("created", "");
        p.port = e.value("port", 4444);
        p.offline = e.value("offline", false);
        p.offlineName = e.value("offlineName", "");
        gProfiles.push_back(p);
    }
}

static Profile* findProfile(const std::string& id) {
    for (auto& p : gProfiles)
        if (p.id == id)
            return &p;
    return nullptr;
}

static bool isRunning(const Profile& p) {
    auto it = gPids.find(p.id);
    if (it == gPids.end())
        return false;
    if (pidAlive(it->second))
        return true;
    gPids.erase(it);
    std::error_code ec;
    fs::remove(instanceDir(p) / "manager.pid", ec);
    return false;
}

static void adoptRunning() {
    for (auto& p : gProfiles) {
        fs::path f = instanceDir(p) / "manager.pid";
        std::error_code ec;
        if (!fs::exists(f, ec))
            continue;
        long pid = std::atol(readFile(f).c_str());
        if (pidAlive(pid))
            gPids[p.id] = pid;
        else
            fs::remove(f, ec);
    }
}

static int nextFreePort() {
    for (int port = 4444; port < 4444 + 10 * 200; port += 10) {
        bool used = false;
        for (auto& p : gProfiles)
            if (p.port == port || p.port == port + 1 || p.port + 1 == port)
                used = true;
        if (!used && portFree(port) && portFree(port + 1))
            return port;
    }
    return 4444;
}

static void copyTree(const fs::path& from, const fs::path& to, const std::string& skipTopLevel) {
    std::error_code ec;
    if (!fs::exists(from, ec))
        return;
    fs::create_directories(to, ec);
    for (auto& e : fs::directory_iterator(from, ec)) {
        std::string name = S(e.path().filename());
        if (!skipTopLevel.empty() && name == skipTopLevel)
            continue;
        fs::copy(e.path(), to / e.path().filename(),
            fs::copy_options::recursive | fs::copy_options::overwrite_existing, ec);
    }
}

