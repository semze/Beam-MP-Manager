    // Copy .zip mods from a file or folder on disk.
    svr.Post("/api/profile/:id/mods/import", [](const httplib::Request& req, httplib::Response& res) {
        std::lock_guard<std::mutex> g(gLock);
        Profile* p = findProfile(req.path_params.at("id"));
        if (!p)
            return sendError(res, 404, "Profile not found");
        if (isRunning(*p))
            return sendError(res, 409, "Stop the game before adding mods");
        json j = json::parse(req.body, nullptr, false);
        if (!j.is_object())
            return sendError(res, 400, "Invalid JSON");
        std::string src = j.value("path", "");
        std::string fromDefault = j.value("fromGame", "");
        std::vector<fs::path> files;
        std::error_code ec;
        if (!fromDefault.empty()) {
            fs::path cur = defaultBeamNGCurrent();
            if (cur.empty() || !fs::exists(cur / "mods", ec))
                return sendError(res, 404, "Could not find your normal BeamNG mods folder");
            for (auto dir : { cur / "mods", cur / "mods" / "repo" })
                for (auto& e : fs::directory_iterator(dir, ec))
                    if (e.is_regular_file(ec) && validModName(S(e.path().filename())))
                        files.push_back(e.path());
        } else {
            fs::path sp = P(src);
            if (src.empty() || !fs::exists(sp, ec))
                return sendError(res, 404, "That path does not exist");
            if (fs::is_directory(sp, ec)) {
                for (auto& e : fs::directory_iterator(sp, ec))
                    if (e.is_regular_file(ec) && validModName(S(e.path().filename())))
                        files.push_back(e.path());
            } else if (validModName(S(sp.filename()))) {
                files.push_back(sp);
            } else {
                return sendError(res, 400, "Only .zip mod files can be imported");
            }
        }
        fs::create_directories(modsDir(*p), ec);
        int copied = 0;
        for (auto& f : files) {
            fs::copy_file(f, modsDir(*p) / f.filename(), fs::copy_options::overwrite_existing, ec);
            if (!ec) {
                fs::remove(disabledDir(*p) / f.filename(), ec);
                copied++;
            }
        }
        sendJson(res, { { "copied", copied }, { "found", (int)files.size() } });
    });

